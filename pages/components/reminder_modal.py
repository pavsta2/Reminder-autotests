    def remove_tag(self, name: str) -> None:
        """
        Удаляет уже выбранный recipient по его тегу внутри поля (не через
        список опций).

        ИСПРАВЛЕНО (2026-11-15) по факту проверки через page.pause() на
        реальном прогоне (тест REMCL-1087 вместо удаления ДОБАВЛЯЛ
        recipient'ов): тег — это MUI Chip
        `<div role="button" data-tag-index="N"><span>ИМЯ</span>
        <button><svg aria-hidden="true">...</svg></button></div>`.
        У ВНЕШНЕГО div роль "button", и его accessible name вычисляется из
        текста содержимого — т.е. совпадает с именем тега (SVG во вложенной
        кнопке aria-hidden, на имя не влияет). А у ВЛОЖЕННОЙ <button>
        (настоящей кнопки удаления) accessible name ПУСТОЙ (нет aria-label,
        видимого текста нет). Поэтому прежний `get_by_role("button",
        name=...)` находил и кликал САМ ЧИП целиком, а не кнопку удаления —
        клик по чипу в этом компоненте удалением не является.

        Теперь: находим чип по ТОЧНОМУУ тексту тега (exact-regex, чтобы не
        задеть, например, тег "Assignee" при поиске тега с похожим именем),
        поднимаемся до ближайшего предка с role="button" (сам чип) и кликаем
        по ЕДИНСТВЕННОЙ кнопке внутри него (вложенной <button> без
        accessible name — такой внутри чипа ровно одна).
        """
        tag_text = self._field.get_by_text(re.compile(rf"^{re.escape(name)}$"))
        chip = tag_text.locator("xpath=ancestor::*[@role='button'][1]")
        chip.get_by_role("button").click()

