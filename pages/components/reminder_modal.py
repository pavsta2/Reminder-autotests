    def wait_for_search_to_settle(self, timeout_ms: int = 10_000) -> None:
        """
        Ждёт, пока пропадёт индикатор 'Loading...' после ввода поискового
        текста.

        ИСПРАВЛЕНО (2026-11-16): между вводом текста (fill() в search()) и
        тем, как индикатор "Loading..." реально появляется на экране, есть
        небольшая задержка (debounce перед серверным запросом) — это
        подтверждено скриншотом из test_search_is_case_insensitive, где
        "Loading..." ещё виден в дропдауне в момент ассерта на результат
        поиска. Старая версия сразу делала `loading.wait_for(state=
        "hidden")` без предварительного ожидания "visible" — если в момент
        вызова индикатор ЕЩЁ не успел показаться (мы всё ещё внутри этой
        задержки), Playwright видит текущее состояние "не видим" и это
        УСЛОВИЕ "hidden" СРАЗУ считается выполненным — метод возвращается
        мгновенно, хотя сам поиск на сервере ещё не завершился. Тест после
        этого проверяет результат раньше времени и падает (или видит
        "Loading..." вместо ожидаемых опций — ровно то, что на скриншоте).

        Фикс: сначала коротко ждём, чтобы индикатор ДЕЙСТВИТЕЛЬНО появился
        (с коротким таймаутом — если ответ пришёл настолько быстро, что
        "Loading..." вовсе не успел показаться, это не ошибка, просто
        игнорируем TimeoutError), и только потом ждём его исчезновения.
        """
        loading = self.frame.get_by_text("Loading...", exact=True)
        try:
            loading.wait_for(state="visible", timeout=1_000)
        except Exception:
            # Либо индикатор не успел показаться (ответ пришёл очень быстро),
            # либо это кэш/повторный поиск без видимого "Loading..." —
            # в обоих случаях не считаем это ошибкой.
            pass
        try:
            loading.wait_for(state="hidden", timeout=timeout_ms)
        except Exception:
            pass

